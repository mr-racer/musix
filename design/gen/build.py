"""Tokens (design/tokens/*.json, DTCG) → one theme per client, from one source:
  gen/web/tokens.css             CSS custom properties (keeps oklch() as authored)
  gen/android/MusixTheme.kt      Compose CompositionLocal theme (sRGB, not Material defaults)
  gen/windows/MusixTheme.xaml    WinUI ResourceDictionary with Dark/Light theme dictionaries
`--check` regenerates in memory and fails on drift (CI runs it).
"""

from __future__ import annotations

import json
import math
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
TOKENS = HERE.parent / "tokens"


# ── colors ───────────────────────────────────────────────────────────────────
def _gamma(c: float) -> float:
    c = max(0.0, min(1.0, c))
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def oklch_to_srgb(lightness: float, chroma: float, hue: float) -> tuple[float, float, float]:
    """OKLCH → gamma-encoded sRGB in [0, 1], clamped (Björn Ottosson's OKLab)."""
    a, b = chroma * math.cos(math.radians(hue)), chroma * math.sin(math.radians(hue))
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    r = 4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_
    g = -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_
    bb = -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_
    return _gamma(r), _gamma(g), _gamma(bb)


def rgba(value: str) -> tuple[int, int, int, float]:
    """Any authored color → (r, g, b, alpha) in sRGB."""
    v = value.strip()
    if m := re.fullmatch(r"#([0-9a-fA-F]{6})", v):
        n = int(m[1], 16)
        return n >> 16, (n >> 8) & 255, n & 255, 1.0
    if m := re.fullmatch(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+))?\s*\)", v):
        return int(m[1]), int(m[2]), int(m[3]), float(m[4] or 1)
    if m := re.fullmatch(r"oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*(?:/\s*([\d.]+))?\s*\)", v):
        r, g, b = oklch_to_srgb(float(m[1]) / 100, float(m[2]), float(m[3]))
        return round(r * 255), round(g * 255), round(b * 255), float(m[4] or 1)
    raise ValueError(f"unsupported color: {value}")


def gradient(value: str) -> tuple[float, list[str]]:
    m = re.fullmatch(r"linear-gradient\(\s*(\d+)deg\s*,(.*)\)", value.strip())
    if not m:
        raise ValueError(f"unsupported gradient: {value}")
    stops = re.findall(r"(#[0-9a-fA-F]{6}|rgba?\([^)]*\)|oklch\([^)]*\))", m[2])
    return float(m[1]), stops


def argb(value: str) -> str:
    r, g, b, a = rgba(value)
    return f"{round(a * 255):02X}{r:02X}{g:02X}{b:02X}"


# ── token loading ────────────────────────────────────────────────────────────
def load() -> dict[str, Any]:
    t: dict[str, Any] = {"color": {}, "motion": {"easing": {}, "duration": {}}, "radius": {}, "blur": {}, "font": {},
                         "type": {}, "space": {}}
    t["color"].update(json.loads((TOKENS / "color.json").read_text())["color"])
    t["motion"].update(json.loads((TOKENS / "motion.json").read_text())["motion"])
    shape = json.loads((TOKENS / "shape.json").read_text())
    t["radius"], t["blur"] = shape["radius"], shape["blur"]
    manual = json.loads((TOKENS / "manual.json").read_text())
    t["color"].update(manual["color"])
    t["font"] = manual["font"]
    t["motion"]["duration"].update(manual["motion"])
    t["type"], t["space"] = manual.get("type", {}), manual.get("space", {})
    return t


def themed(tok: dict[str, Any], theme: str) -> str:
    v = tok["$value"]
    return v[theme] if isinstance(v, dict) else v


def kebab(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z0-9])", "-", name).lower()


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


# ── emitters ─────────────────────────────────────────────────────────────────
def css(t: dict[str, Any]) -> str:
    out = ["/* GENERATED by design/gen/build.py from design/tokens — do not edit. */", ":root {"]
    out += [f"  --mx-font-{kebab(k)}: {', '.join(repr(f) if ' ' in f else f for f in v['$value'])};"
            for k, v in t["font"].items()]
    out += [f"  --mx-ease-{k}: cubic-bezier({', '.join(str(x) for x in v['$value'])});"
            for k, v in t["motion"]["easing"].items()]
    out += [f"  --mx-dur-{kebab(k)}: {v['$value']};" for k, v in t["motion"]["duration"].items()]
    out += [f"  --mx-radius-{k[1:]}: {v['$value']};" for k, v in t["radius"].items()]
    out += [f"  --mx-blur-{k[1:]}: {v['$value']};" for k, v in t["blur"].items()]
    out += [f"  --mx-type-{k}: {v['$value']};" for k, v in t["type"].items()]
    out += [f"  --mx-space-{k[1:]}: {v['$value']};" for k, v in t["space"].items()]
    out.append("}")
    for theme in ("dark", "light"):
        scope = ', [data-mx-theme="dark"]' if theme == "dark" else ""  # a dark surface in a light app
        out.append(f':root[data-theme="{theme}"]{scope} {{')
        out += [f"  --mx-{kebab(k)}: {themed(v, theme)};" for k, v in t["color"].items()]
        out.append("}")
    return "\n".join(out) + "\n"


def kotlin(t: dict[str, Any]) -> str:
    colors = t["color"]
    fields = [f"    val {k}: {'MusixGradient' if v['$type'] == 'gradient' else 'Color'}," for k, v in colors.items()]

    def inst(theme: str) -> list[str]:
        rows = []
        for k, v in colors.items():
            val = themed(v, theme)
            if v["$type"] == "gradient":
                angle, stops = gradient(val)
                rows.append(f"    {k} = MusixGradient({angle}f, listOf({', '.join(f'Color(0x{argb(s)})' for s in stops)})),")
            else:
                rows.append(f"    {k} = Color(0x{argb(val)}),")
        return rows

    out = ["// GENERATED by design/gen/build.py from design/tokens — do not edit.",
           "package ru.musixai.app.core.designsystem", "",
           "import androidx.compose.animation.core.CubicBezierEasing",
           "import androidx.compose.runtime.Immutable",
           "import androidx.compose.runtime.staticCompositionLocalOf",
           "import androidx.compose.ui.graphics.Color",
           "import androidx.compose.ui.unit.dp",
           "import androidx.compose.ui.unit.sp", "",
           "/** A CSS linear-gradient: angle in degrees (CSS convention) and its color stops. */",
           "@Immutable", "data class MusixGradient(val angleDeg: Float, val colors: List<Color>)", "",
           "@Immutable", "data class MusixColors(", *fields, ")", "",
           "val DarkMusixColors = MusixColors(", *inst("dark"), ")", "",
           "val LightMusixColors = MusixColors(", *inst("light"), ")", "",
           "val LocalMusixColors = staticCompositionLocalOf { DarkMusixColors }", "",
           "object MusixMotion {"]
    out += [f"    val {pascal(k)} = CubicBezierEasing({', '.join(f'{x}f' for x in v['$value'])})"
            for k, v in t["motion"]["easing"].items()]
    out += [f"    const val {pascal(k)}Ms = {v['$value'].removesuffix('ms')}" for k, v in t["motion"]["duration"].items()]
    out += ["}", "", "object MusixShape {"]
    out += [f"    val Radius{k[1:]} = {v['$value'].removesuffix('px')}.dp" for k, v in t["radius"].items()]
    out += [f"    val Blur{k[1:]} = {v['$value'].removesuffix('px')}.dp" for k, v in t["blur"].items()]
    out += ["}", "", "object MusixScale {"]
    out += [f"    val {pascal(k)} = {v['$value'].removesuffix('px')}.sp" for k, v in t["type"].items()]
    out += ["}", "", "object MusixSpace {"]
    out += [f"    val {pascal(k)} = {v['$value'].removesuffix('px')}.dp" for k, v in t["space"].items()]
    out += ["}", "", "object MusixFonts {"]
    out += [f'    const val {pascal(k)} = "{v["$value"][0]}"' for k, v in t["font"].items()]
    out.append("}")
    return "\n".join(out) + "\n"


def xaml(t: dict[str, Any]) -> str:
    def theme_dict(theme: str) -> list[str]:
        rows = [f'    <ResourceDictionary x:Key="{theme.capitalize()}">']
        for k, v in t["color"].items():
            val = themed(v, theme)
            if v["$type"] == "gradient":
                angle, stops = gradient(val)
                rad = math.radians(angle - 90)  # CSS 0deg points up; XAML points are 0..1
                x, y = math.cos(rad) / 2, math.sin(rad) / 2
                rows.append(f'      <LinearGradientBrush x:Key="Mx{pascal(k)}" StartPoint="{0.5 - x:.3f},{0.5 - y:.3f}" '
                            f'EndPoint="{0.5 + x:.3f},{0.5 + y:.3f}">')
                n = len(stops)
                rows += [f'        <GradientStop Color="#{argb(s)}" Offset="{i / max(1, n - 1):.3f}"/>' for i, s in enumerate(stops)]
                rows.append("      </LinearGradientBrush>")
            else:
                rows.append(f'      <Color x:Key="Mx{pascal(k)}">#{argb(val)}</Color>')
        rows.append("    </ResourceDictionary>")
        return rows

    out = ["<!-- GENERATED by design/gen/build.py from design/tokens — do not edit. -->",
           '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
           '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
           "  <ResourceDictionary.ThemeDictionaries>", *theme_dict("dark"), *theme_dict("light"),
           "  </ResourceDictionary.ThemeDictionaries>"]
    out += [f'  <x:Double x:Key="MxRadius{k[1:]}">{v["$value"].removesuffix("px")}</x:Double>' for k, v in t["radius"].items()]
    out += [f'  <x:Double x:Key="MxType{pascal(k)}">{v["$value"].removesuffix("px")}</x:Double>' for k, v in t["type"].items()]
    out += [f'  <x:Double x:Key="MxSpace{k[1:]}">{v["$value"].removesuffix("px")}</x:Double>' for k, v in t["space"].items()]
    out += [f'  <x:String x:Key="MxFont{pascal(k)}">{v["$value"][0]}</x:String>' for k, v in t["font"].items()]
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


OUTPUTS = {"web/tokens.css": css, "android/MusixTheme.kt": kotlin, "windows/MusixTheme.xaml": xaml}


def main() -> None:
    t = load()
    drift = []
    for rel, fn in OUTPUTS.items():
        path = HERE / rel
        text = fn(t)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                drift.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if drift:
        raise SystemExit(f"design drift: {', '.join(drift)} — run `make design` and commit")
    print("design: " + ("in sync" if "--check" in sys.argv else "generated " + ", ".join(OUTPUTS)))


if __name__ == "__main__":
    main()
